uint32_t crc32(const uint8_t *data, size_t len) {
    uint32_t crc = 0xFFFFFFFF;
    while (len--) {
        crc = crc32_table[(crc ^ *data++) & 0xFF] ^ (crc >> 8);
    }
    return crc ^ 0xFFFFFFFF;
}

/* Parse IP from string "192.168.1.1" */
int parse_ip(const char *str, uint32_t *out) {
    if (!str || !out) return -1;
    
    uint32_t ip = 0;
    int octet = 0;
    int val = 0;
    
    while (*str && octet < 4) {
        if (*str >= '0' && *str <= '9') {
            val = val * 10 + (*str - '0');
        } else if (*str == '.') {
            ip = (ip << 8) | (val & 0xFF);
            val = 0;
            octet++;
        } else {
            return -1;
        }
        str++;
    }
    
    if (octet != 3) return -1;
    ip = (ip << 8) | (val & 0xFF);
    *out = ip;
    return 0;
}
